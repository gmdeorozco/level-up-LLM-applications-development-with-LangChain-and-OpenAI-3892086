# Load the sample data (PDF document)
loader = PyPDFLoader("imitacion_de_cristo.pdf")
data = loader.load()

# Split PDF into smaller documents
# Adjusted chunk_size for potentially larger documents if k=10 is used
# Although 200 is fine, ensure it's not too small if you want rich context
text_splitter = RecursiveCharacterTextSplitter(chunk_size=500, chunk_overlap=50) 
docs = text_splitter.split_documents(data)

# Print the first document
print(docs[0])

# Instantiate the vector store
vector_store = MongoDBAtlasVectorSearch.from_documents(
    documents=docs,
    embedding=OpenAIEmbeddings(disallowed_special=()),
    collection=collection, # Corrected in previous step
    index_name=ATLAS_VECTOR_SEARCH_INDEX_NAME # Fix: this might be a typo, should be ATLAS_VECTOR_SEARCH_INDEX_NAME
)

# ... (rest of your imports and setup)

# Instantiate Atlas Vector Search as a retriever
retriever = vector_store.as_retriever(
    search_type="similarity", search_kwargs={"k": 10}
)

# Define a prompt template
template = """
    Use the following pieces of context to answer the question at the end.
    If you don't know the answer, just say that you don't know, don't try to make up an answer.
    {context}
    Question: {question}
"""

custom_rag_prompt = PromptTemplate.from_template(template)

# This function will take a list of Document objects and return a single string
def format_docs(docs):
    return "\n\n".join(doc.page_content for doc in docs)

# Construct a chain to answer questions on your data
rag_chain = (
    # Step 1: Get the question and retrieve documents.
    # The output of this step will be {"question": ..., "context": [list of Document objects]}
    {"context": retriever, "question": RunnablePassthrough()}
    # Step 2: Debug the retrieved context (which are still Document objects here).
    # The output will remain {"question": ..., "context": [list of Document objects]}
    | RunnablePassthrough.assign(
        # Pass the current 'context' (list of Documents) to the debug function
        # The result of debug_chain_input isn't added to the main flow, it just prints.
        # So we use a lambda that returns the context, keeping the flow clean.
        debug_retrieved_context=RunnableLambda(lambda x: debug_chain_input({"context": x["context"], "question": x["question"]}))
    )
    # Step 3: Format the 'context' from list of Documents to a single string.
    # The input to this step is {"question": ..., "context": [list of Document objects]}.
    # The output of this step will be {"question": ..., "context": "formatted string"}
    | {"context": RunnableLambda(lambda x: format_docs(x["context"])),
       "question": RunnablePassthrough()}
    # Step 4: Apply the custom prompt template.
    # The input to this step is {"question": ..., "context": "formatted string"}.
    # The output of this step is a PromptValue object.
    | custom_rag_prompt
    # Step 5: Debug the final prompt sent to the LLM.
    | RunnableLambda(debug_prompt_output)
    # Step 6: Invoke the LLM.
    | model
    # Step 7: Parse the output.
    | StrOutputParser()
)

# Prompt the chain to answer a question
question = "Dime una enseñanza sobre la muerte"
answer = rag_chain.invoke(question)
print(answer)