def debug_prompt_output(prompt_value_object):
    """
    Debugs the PromptValue object generated by a LangChain prompt template within a chain.
    It prints the content of the prompt (as a string or list of messages).
    """
    print("\n--- DEBUG: Prompt Sent to LLM ---")
    
    # Check if it's a string prompt or a chat prompt
    if hasattr(prompt_value_object, "to_string"):
        # For simple string prompts
        print("Rendered Prompt (as string):\n", prompt_value_object.to_string())
    elif hasattr(prompt_value_object, "to_messages"):
        # For chat prompts (list of messages)
        print("Rendered Prompt (as messages):")
        for msg in prompt_value_object.to_messages():
            if isinstance(msg, SystemMessage):
                print(f"System Message: {msg.content}")
            elif isinstance(msg, HumanMessage):
                print(f"Human Message: {msg.content}")
            elif isinstance(msg, AIMessage):
                print(f"AI Message: {msg.content}")
            else:
                print(f"Other Message Type ({type(msg).__name__}): {str(msg)}")
    else:
        # Fallback for unexpected prompt value types
        print("Rendered Prompt (raw object):\n", prompt_value_object)
    
    print("--- END DEBUG ---\n")
    
    return prompt_value_object # IMPORTANT: Pass the object through to the next step

# This debug function is placed before the prompt template to see what's being passed as context
def debug_chain_input(input_dict):
    # input_dict will have 'context' and 'question'
    context_docs = input_dict["context"]
    question = input_dict["question"]

    full_context_text = "\n\n".join([doc.page_content for doc in context_docs])
    print("\n--- DEBUG: Retrieved Context ---")
    print(f"Number of documents retrieved: {len(context_docs)}")
    print(f"Total characters in retrieved context: {len(full_context_text)}")
    print(f"Question: {question}")
    print("--- END DEBUG ---\n")
    # Pass through the original input for the next step in the chain
    return input_dict

